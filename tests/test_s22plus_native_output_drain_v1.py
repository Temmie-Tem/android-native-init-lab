_original_source=base.source

def producer_source(*,corrected=True):
    value=_original_source()
    identity=source.resident.common.Identity('p998',base.RUN.hex(),'v0.2.2-rc.1')
    helper=(source if corrected else source.previous).helper_template(identity).decode()
    begin=helper.index('#define RC1_RUN_ID_ASCII')
    end=helper.index('/* Return 1 only after authenticated CONTROL ACK',begin)
    start=value.index('#define RC1_RUN_ID_ASCII')
    stop=value.index('static long rc1_console(',start)
    value=value[:start]+helper[begin:end]+'''
static long baseline_check(void){return 0;}
static int baseline_detach_available(void){return 1;}
static void resident_export_current(void){}
'''+value[stop:]
    value=value.replace('static void p282_poll_delay(void){usleep(1000);}',
        'static void p282_poll_delay(void){usleep(100000);}')
    # Fix capacity so the producer exits with >2 seconds of buffered bytes.
    old='static long sys_pipe2(int *fds,int flags){ return neg(pipe2(fds,flags)); }'
    new='''static long sys_pipe2(int *fds,int flags){
 long rc=neg(pipe2(fds,flags));if(rc)return rc;
 if(fcntl(fds[0],F_SETPIPE_SZ,65536)!=65536)_exit(91);return 0;
}'''
    assert value.count(old)==1
    return value.replace(old,new)


class Arm64DrainTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        with mock.patch.object(base,'source',producer_source):
            arm64.Arm64ConsoleTests.setUpClass.__func__(cls)

    setUp=base.ConsoleTests.setUp
    tearDown=base.ConsoleTests.tearDown
    wait=base.ConsoleTests.wait
    output=base.ConsoleTests.output
    finish=base.ConsoleTests.finish

    def burst(self,timeout=15000):
        busybox=shlex.quote(self.launcher[0])+' '+shlex.quote(str(self.folder/'busybox'))
        command=(busybox+' head -c 49152 /dev/zero; printf ERR >&2').encode()
        # Binary data is generated by the actual packaged ARM64 BusyBox.
        seq=self.session.send(wire.EXEC,wire.command(command,timeout_ms=timeout))
        self.wait(wire.ACK,seq)
        return seq,b'\0'*49152

    def test_reaped_buffered_output_survives_two_seconds_and_paused_reader(self):
        seq,wanted=self.burst()
        time.sleep(2.5)
        status=self.session.send(wire.STATUS)
        self.wait(wire.STATUS_REPLY,status)
        end=struct.unpack('<7I',self.wait(wire.EXIT,seq,timeout=14))
        self.assertEqual(end[1:4],(0,0,0))
        self.assertEqual(end[4:6],(len(wanted)+3,0))
        self.assertEqual(self.output(seq,1),wanted)
        self.assertEqual(self.output(seq,2),b'ERR')
        # The short stderr stream must not wait for the stdout backlog.
        kinds=[struct.unpack('<I',b[8:12])[0] for k,n,b in self.events if k==wire.OUTPUT and n==seq]
        self.assertLess(kinds.index(2),len(kinds)-2)
        self.finish()

    def test_original_deadline_still_stops_incomplete_buffered_output(self):
        seq,_=self.burst(timeout=500)
        end=struct.unpack('<7I',self.wait(wire.EXIT,seq,timeout=5))
        self.assertEqual(end[1]&0x8a,0x8a)
        self.assertLess(end[4],49155)
        self.finish()

    def test_cancel_keeps_bounded_incomplete_terminal(self):
        seq,_=self.burst()
        cancel=self.session.send(wire.CANCEL,struct.pack('<I',seq))
        self.wait(wire.ACK,cancel)
        end=struct.unpack('<7I',self.wait(wire.EXIT,seq,timeout=5))
        self.assertEqual(end[1]&0x89,0x89)
        self.finish()

    def test_control_during_output_preserves_honest_terminal(self):
        seq,_=self.burst()
        self.finish()
        end=struct.unpack('<7I',self.wait(wire.EXIT,seq))
        self.assertEqual(end[1]&0xa8,0xa8)
        self.assertLess(end[4],49155)

    def test_background_descendant_is_terminated_and_reaped_before_clean_exit(self):
        busybox=shlex.quote(self.launcher[0])+' '+shlex.quote(str(self.folder/'busybox'))
        command=(busybox+" sh -c 'trap \"\" TERM; while :; do :; done' & printf END").encode()
        seq=self.session.send(wire.EXEC,wire.command(command,timeout_ms=5000))
        end=struct.unpack('<7I',self.wait(wire.EXIT,seq,timeout=5))
        self.assertEqual(end[1:4],(0,0,0));self.assertEqual(self.output(seq,1),b'END')
        self.finish()


