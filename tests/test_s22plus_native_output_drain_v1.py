class DetachTests(unittest.TestCase):
    def test_unsettled_group_keeps_two_second_cleanup_stop(self):
        # A controlled unkillable-group result exercises the failure branch;
        # no host process is signalled. Pipe behavior and production tick are real.
        text=producer_source();text=text[:text.index('int main(int argc,char **argv)')]
        old='static long sys_kill(long pid,int sig){ return neg(kill(pid,sig)); }'
        self.assertEqual(text.count(old),1)
        text=text.replace(old,'static long sys_kill(long pid,int sig){(void)pid;(void)sig;return 0;}')
        text+='''
#include <assert.h>
int main(void){
 int p[2];assert(!pipe2(p,O_NONBLOCK|O_CLOEXEC));
 struct rc1_state s={0};s.pid=12345;s.id=3;s.active=1;s.reaped=1;s.exec_seen=1;
 s.timeout=15000;s.command_start=1000;s.cancel_phase=1;s.cancel_start=1000;
 s.pipe[0]=p[0];s.pipe[1]=-1;s.pipe[2]=-1;
 assert(!rc1_child_tick(&s,2999));assert(s.active&&!s.blocked&&!s.terminal_sent);
 assert(!rc1_child_tick(&s,3000));assert(!s.active&&s.blocked&&s.terminal_sent);
 assert(s.flags==(RC1_FLAG_CLEANUP|RC1_FLAG_OUTPUT_INCOMPLETE));
 assert(s.pid==12345&&s.pipe[0]<0);close(p[1]);return 0;
}
'''
        with tempfile.TemporaryDirectory() as folder:
            binary=Path(folder)/'unsettled'
            built=subprocess.run(['cc','-x','c','-','-O2','-Wall','-Wextra','-Werror',
                '-Wno-unused-function','-Wno-misleading-indentation','-o',str(binary)],
                input=text,text=True,capture_output=True,timeout=30)
            self.assertEqual(built.returncode,0,built.stderr)
            subprocess.run([str(binary)],check=True,timeout=3)

    def test_terminal_flags_block_detach_without_any_write_but_nonzero_status_does_not(self):
        for flags,status,dropped in ((0x88,0,0),(1,15,0),(2,15,0),(4,0,1),(0,7<<8,0)):
            with self.subTest(flags=flags),tempfile.TemporaryDirectory() as folder:
                host,peer=socket.socketpair()
                host.setblocking(False);peer.setblocking(False)
                self.addCleanup(host.close);self.addCleanup(peer.close)
                session=protocol.Session(host.fileno(),base.KEY,base.RUN,base.NONCE,Path(folder)/'session')
                self.addCleanup(session.close)
                session.ready=(1,600000,300000,1048576,767,255,0,0)
                session.requests[3]=wire.EXEC;session.request_bodies[3]=wire.command(b'exit 7')
                session.accepted.add(3);session.sequence=4
                session._validate(wire.EXIT,3,struct.pack('<7I',3,flags,status,0,0,dropped,0))
                with mock.patch.object(wire.Session,'send',return_value=4) as send:
                    if flags:
                        with self.assertRaisesRegex(wire.ProtocolError,'complete idle'):
                            session.send(protocol.DETACH)
                        send.assert_not_called()
                    else:
                        self.assertEqual(session.send(protocol.DETACH),4)
                        send.assert_called_once()


